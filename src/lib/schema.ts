import { z } from "zod";
export const fieldsSchema = z.strictObject({
  name: z.string().trim().min(1, "请填写商品名称").max(120),
  sku: z.string().trim().max(120).default(""),
  supplier: z.string().trim().max(200).default(""),
  supplierContact: z.string().trim().max(200).default(""),
  colors: z.string().trim().max(200).default(""),
  material: z.string().trim().max(200).default(""),
  dimensions: z.string().trim().max(200).default(""),
  weightG: z.number().finite().nonnegative().max(100000000).nullable().default(null),
  unitPrice: z.number().finite().nonnegative().max(100000000).nullable().default(null),
  currency: z.enum(["CNY", "USD", "EUR"]).default("CNY"),
  moq: z.number().int().nonnegative().max(100000000).nullable().default(null),
  cartonQty: z.number().int().positive().max(100000000).nullable().default(null),
  cartons: z.number().int().nonnegative().max(100000000).nullable().default(null),
  quantity: z.number().int().nonnegative().max(100000000).nullable().default(null),
  exportRemarks:z.string().trim().max(5000).default(''),
  barcode: z.string().trim().max(200).default(''),
  custom: z.record(z.string().regex(/^[a-z][a-z0-9_]{0,39}$/),z.string().max(2000)).refine(v=>Object.keys(v).length<=40,'扩展字段过多').default({}),
  cartonDimensions: z.string().trim().max(200).default(""),
  cartonCbm: z.number().finite().nonnegative().max(100000000).nullable().default(null),
  leadTimeDays: z.number().int().nonnegative().max(100000000).nullable().default(null),
  tradeTerms: z.string().trim().max(200).default(""),
  description: z.string().max(10000).default(""),
  notes: z.string().max(5000).default(""),
  confirmed: z.boolean().default(false),
  favorite: z.boolean().default(false),
  rating: z.number().int().min(1).max(5).nullable().default(null),
  evaluation: z.string().max(5000).default(''),
});
export const projectSchema = z.object({ name: z.string().trim().min(1, "请填写任务名称").max(120), market: z.string().trim().max(120), date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).refine(value => !Number.isNaN(Date.parse(value)) && new Date(value).toISOString().slice(0,10) === value, "日期无效") });
export const extractionSchema = z.object({
  exportRemarks:z.string().max(5000).nullable().optional(),
  cartons:z.number().int().nonnegative().max(100000000).nullable().optional(),
  quantity:z.number().int().nonnegative().max(100000000).nullable().optional(),
  barcode:z.string().max(200).nullable().optional(),
  name: z.string().max(120).nullable(), colors: z.string().max(200).nullable(), material: z.string().max(200).nullable(),
  dimensions: z.string().max(200).nullable(), weightG: z.number().finite().nonnegative().max(100000000).nullable(),
  unitPrice: z.number().finite().nonnegative().max(100000000).nullable(), currency: z.enum(["CNY","USD","EUR"]).nullable(),
  moq: z.number().int().nonnegative().max(100000000).nullable(), cartonQty: z.number().int().positive().max(100000000).nullable(),
  supplier: z.string().max(200).nullable().optional(),
  supplierContact: z.string().max(200).nullable().optional(),
  notes: z.string().max(5000).nullable().optional(),
  sku: z.string().max(120).nullable().optional(),
  cartonDimensions: z.string().max(200).nullable().optional(),
  cartonCbm: z.number().finite().nonnegative().max(100000000).nullable().optional(),
  leadTimeDays: z.number().int().nonnegative().max(100000000).nullable().optional(),
  tradeTerms: z.string().max(200).nullable().optional(),
}).strict();
